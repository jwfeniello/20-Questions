"""CLI, malformed-container rejection and reproducible data generation."""
import argparse,hashlib,json,pathlib,subprocess,sys
ROOT=pathlib.Path(__file__).resolve().parents[1]
def main(exe,dll):
    tests=[]
    for lang in ['en','de','es','fr','it','jp']:
        r=subprocess.run([str(exe),'--bank',lang,'--seed','1','--trace'],cwd=ROOT,input='1\nN\nY\ncandidates\nrestart\nquit\n',text=True,encoding='utf8',capture_output=True)
        assert r.returncode==0,(lang,r.stderr);assert 'New game, same seed.' in r.stdout and 'random_calls=' in r.stdout and 'id=0 counter=1' in r.stdout
        (ROOT/'reports'/f'cli-{lang}.txt').write_text(r.stdout,encoding='utf8');tests.append({'bank':lang,'status':'PASS'})
    r=subprocess.run([str(exe),'--bank','el'],cwd=ROOT,capture_output=True);assert r.returncode!=0 and b'unsupported' in r.stderr
    # Actual runnable transcript, generated by the native generator (not hooks).
    from compare import Native,getword
    n=Native(dll);answers=[];target=1
    for _ in range(80):
        assert n.d.q20_advance(n.game)>=0;s=n.state();kind=getword(s,8);id=getword(s,12)
        if kind==99:break
        if kind==1:answer=2 # carrot -> Vegetable
        elif kind==3:answer=2 if id==target else 1
        else:answer={0:0,1:5,2:7,4:1,9:6,10:8,12:2}[n.d.q20_read(n.model,id,target,4)]
        answers.append(str(answer));assert n.d.q20_submit(n.game,answer)==0
    assert kind==99 and getword(s,24)==target;n.close()
    script='\n'.join(answers+['quit'])+'\n';r=subprocess.run([str(exe),'--seed','1','--trace'],cwd=ROOT,input=script,text=True,encoding='utf8',capture_output=True)
    assert r.returncode==0 and 'I guessed it: a carrot!' in r.stdout
    (ROOT/'tests/carrot-input.txt').write_text(script);(ROOT/'reports/cli-complete.txt').write_text(r.stdout,encoding='utf8')
    tests.append({'case':'complete native-seeded CLI game','answers':len(answers),'guess':'a carrot'})
    bad=ROOT/'reports/corrupt.q20';data=bytearray((ROOT/'data/en.q20').read_bytes());data[-1]^=1;bad.write_bytes(data)
    r=subprocess.run([str(exe),'--model',str(bad)],cwd=ROOT,capture_output=True);assert r.returncode!=0 and b'corrupt' in r.stderr;bad.unlink();tests.append({'case':'CRC-corrupt container rejected','status':'PASS'})
    regen=ROOT/'reports/regenerated-models';subprocess.run([sys.executable,str(ROOT/'tools/prepare_models.py'),'--source',str(ROOT.parent/'output/data'),'--out',str(regen)],check=True,capture_output=True)
    for p in (ROOT/'data').glob('*'):assert p.read_bytes()==(regen/p.name).read_bytes()
    tests.append({'case':'all model containers and manifest reproduce byte-for-byte','status':'PASS'})
    # Audit protected extraction tree against its prior delivery manifest.
    output=ROOT.parent/'output';manifest=json.loads((output/'deliverables_manifest.json').read_text())
    for row in manifest['files']:assert hashlib.sha256((output/row['path']).read_bytes()).hexdigest()==row['sha256'],row['path']
    tests.append({'case':'original extraction deliverables unchanged','files_checked':len(manifest['files'])})
    (ROOT/'reports/smoke.json').write_text(json.dumps(tests,indent=2)+'\n');print('CLI, container, reproduction and preservation checks PASS')
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--exe',type=pathlib.Path,required=True);p.add_argument('--library',type=pathlib.Path,required=True);a=p.parse_args();main(a.exe.resolve(),a.library.resolve())
